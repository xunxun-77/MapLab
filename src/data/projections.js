export const PROJECTION_MAP = new Map(PROJECTIONS.map((projection) => [projection.id, projection]))

export const DEFAULT_SETTINGS = {
  longitude: 105,
  latitude: 35,
  parallel1: 25,
  parallel2: 47,
  standardParallel: 45,
  centralScale: 1,
}

export function getProjection(id) {
  return PROJECTION_MAP.get(id) ?? PROJECTIONS[3]
}

export function settingsForProjection(id, fallback = DEFAULT_SETTINGS) {
  const projection = getProjection(id)
  return {
    ...fallback,
    ...projection.defaults,
  }
}
